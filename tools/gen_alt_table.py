#!/usr/bin/env python3
"""Generate the pressure -> altitude table used by src/altitude.c.

Standard atmosphere: h = 44330 * (1 - (P / 101325) ^ 0.1903), in 0.1 m,
sampled every 1024 Pa from 86016 to 106496 Pa (about +1.3 km to -430 m;
outside that it clamps). Linear interpolation stays within ~0.1 m.
"""

SHIFT = 10           # STEP = 1024 Pa, so the 8051 can shift instead of divide
STEP = 1 << SHIFT
PMIN = 84 * STEP     # 86016 Pa, about +1.3 km
PMAX = 104 * STEP    # 106496 Pa, about -430 m
OFFSET = 4500        # 0.1 m; stored values are h + OFFSET so they fit uint16


def h(p):
    return 44330.0 * (1.0 - (p / 101325.0) ** 0.1903)


def table():
    return [round(h(p) * 10) for p in range(PMIN, PMAX + 1, STEP)]


def interp(t, p):
    if p <= PMIN:
        return t[0]
    if p >= PMAX:
        return t[-1]
    i, f = (p - PMIN) >> SHIFT, (p - PMIN) & (STEP - 1)
    return t[i] + (((t[i + 1] - t[i]) * f + STEP // 2) >> SHIFT)


if __name__ == "__main__":
    import sys
    t = table()
    if "--check" in sys.argv:
        worst = 0
        for p in range(PMIN, PMAX, 7):
            err = interp(t, p) / 10 - h(p)
            worst = max(worst, abs(err))
        print(f"max |error| {worst:.3f} m")
        for p in (100000, 101325, 90000, 87000):
            print(p, interp(t, p) / 10, round(h(p), 2))
        sys.exit()
    assert min(t) + OFFSET >= 0 and max(t) + OFFSET <= 0xFFFF
    print(f"/* generated by tools/gen_alt_table.py: {PMIN}..{PMAX} Pa step {STEP},"
          f" 0.1 m + {OFFSET} */")
    for i in range(0, len(t), 8):
        print("\t" + " ".join(f"{v + OFFSET}," for v in t[i:i + 8]))
