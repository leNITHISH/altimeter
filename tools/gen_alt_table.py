#!/usr/bin/env python3
"""Generate the pressure -> altitude table used by src/altitude.c.

Standard atmosphere: h = 44330 * (1 - (P / 101325) ^ 0.1903), in 0.1 m,
sampled every STEP Pa from PMIN to PMAX. Linear interpolation between
1 kPa points stays within ~0.1 m near sea level.
"""

PMIN, PMAX, STEP = 50000, 110000, 1000


def h(p):
    return 44330.0 * (1.0 - (p / 101325.0) ** 0.1903)


def table():
    return [round(h(p) * 10) for p in range(PMIN, PMAX + 1, STEP)]


def interp(t, p):
    i, f = divmod(p - PMIN, STEP)
    if i >= len(t) - 1:
        return t[-1]
    return t[i] + (t[i + 1] - t[i]) * f // STEP


if __name__ == "__main__":
    import sys
    t = table()
    if "--check" in sys.argv:
        worst = 0
        for p in range(PMIN, PMAX, 7):
            err = interp(t, p) / 10 - h(p)
            worst = max(worst, abs(err))
        print(f"max |error| {worst:.3f} m")
        for p in (100000, 101325, 90000, 60000):
            print(p, interp(t, p) / 10, round(h(p), 2))
        sys.exit()
    print(f"/* generated by tools/gen_alt_table.py: {PMIN}..{PMAX} Pa step {STEP}, 0.1 m */")
    for i in range(0, len(t), 6):
        print("\t" + " ".join(f"{v}," for v in t[i:i + 6]))
